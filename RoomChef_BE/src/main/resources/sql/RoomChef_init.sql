-- ==========================================================
-- 방구석 셰프 (RoomChef) 데이터베이스 초기화 DDL
-- 대상 DBMS: Oracle Database 19c+ / 호환 SQL
-- ==========================================================

-- 1. USERS (사용자 테이블)
CREATE TABLE USERS (
    USER_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOGIN_ID        VARCHAR2(50) NOT NULL UNIQUE,
    PASSWORD        VARCHAR2(256) NOT NULL,
    NICKNAME        VARCHAR2(50) NOT NULL UNIQUE,
    EMAIL           VARCHAR2(100) NOT NULL UNIQUE,
    ROLE_CODE       NUMBER DEFAULT 1 NOT NULL, -- 1: 일반, 9: 관리자
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 2. RECIPES (요리 레시피 마스터)
CREATE TABLE RECIPES (
    RECIPE_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE           VARCHAR2(200) NOT NULL,
    SOURCE_TYPE     VARCHAR2(30) NOT NULL, -- YOUTUBE, PUBLIC_API, USER_CUSTOM
    CHANNEL_NAME    VARCHAR2(100),         -- ex) 자취요리신, 뚝딱이형, 식품안전나라
    VIDEO_URL       VARCHAR2(500),
    THUMBNAIL_URL   VARCHAR2(500),
    COOK_TIME_MIN   NUMBER DEFAULT 15,
    DIFFICULTY      VARCHAR2(20) DEFAULT 'EASY', -- EASY, MEDIUM, HARD
    SERVINGS        NUMBER DEFAULT 1,            -- 1인분 기준
    ONE_PAN_YN      CHAR(1) DEFAULT 'N',         -- 원팬 요리 여부
    MICROWAVE_YN    CHAR(1) DEFAULT 'N',         -- 전자레인지 가능 여부
    SCORE_WEIGHT    NUMBER(5, 2) DEFAULT 1.0,    -- AI 추천 노출 가중치 (기본 1.0)
    VIEW_COUNT      NUMBER DEFAULT 0,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 3. RECIPE_INGREDIENTS (레시피 식재료)
CREATE TABLE RECIPE_INGREDIENTS (
    INGREDIENT_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RECIPE_ID       NUMBER NOT NULL REFERENCES RECIPES(RECIPE_ID) ON DELETE CASCADE,
    INGREDIENT_NAME VARCHAR2(100) NOT NULL,      -- ex) 스팸, 양파, 진간장
    AMOUNT          VARCHAR2(50),                -- ex) 1/2캔, 1개, 2스푼
    UNIT            VARCHAR2(30),                -- ex) 개, 스푼, 캔, g
    IS_ESSENTIAL    CHAR(1) DEFAULT 'Y',         -- 필수 재료 여부
    IS_BASIC_SAUCE  CHAR(1) DEFAULT 'N'          -- 기본 양념(자취방 필수) 여부
);

-- 4. RECIPE_STEPS (레시피 조리 순서)
CREATE TABLE RECIPE_STEPS (
    STEP_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RECIPE_ID       NUMBER NOT NULL REFERENCES RECIPES(RECIPE_ID) ON DELETE CASCADE,
    STEP_ORDER      NUMBER NOT NULL,
    INSTRUCTION     VARCHAR2(1000) NOT NULL,
    TIMER_SECONDS   NUMBER DEFAULT 0,            -- 조리 타이머(초 단위)
    TIP             VARCHAR2(500)
);

-- 5. FRIDGE_INGREDIENTS (내 냉장고 속 식재료)
CREATE TABLE FRIDGE_INGREDIENTS (
    FRIDGE_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID         NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    INGREDIENT_NAME VARCHAR2(100) NOT NULL,
    QUANTITY        VARCHAR2(50),
    EXPIRE_DATE     DATE,
    REGISTERED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 6. RECIPE_EVALUATIONS (사용자 직접 요리 평가 및 평점 피드백)
-- 3점: 유지(가중치 변동 없음)
-- 4~5점: 추천 가산점 (+)
-- 1~2점: 추천 감점 (-)
CREATE TABLE RECIPE_EVALUATIONS (
    EVAL_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID         NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    RECIPE_ID       NUMBER NOT NULL REFERENCES RECIPES(RECIPE_ID) ON DELETE CASCADE,
    RATING          NUMBER(2, 1) NOT NULL, -- 1.0 ~ 5.0
    FEEDBACK_NOTE   VARCHAR2(1000),
    EVALUATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_EVAL_USER_RECIPE UNIQUE (USER_ID, RECIPE_ID)
);

-- 7. RECIPE_WEIGHT_LOG (일일 스케줄러에 의한 AI 추천 가중치 재계산 이력)
CREATE TABLE RECIPE_WEIGHT_LOG (
    LOG_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BATCH_DATE      DATE DEFAULT SYSDATE NOT NULL,
    RECIPES_UPDATED NUMBER NOT NULL,
    AVG_SCORE       NUMBER(4, 2),
    LOG_DETAIL      VARCHAR2(1000),
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 인덱스 생성
CREATE INDEX IDX_RECIPES_WEIGHT ON RECIPES(SCORE_WEIGHT DESC);
CREATE INDEX IDX_INGREDIENTS_NAME ON RECIPE_INGREDIENTS(INGREDIENT_NAME);
CREATE INDEX IDX_FRIDGE_USER ON FRIDGE_INGREDIENTS(USER_ID);
CREATE INDEX IDX_EVAL_RECIPE ON RECIPE_EVALUATIONS(RECIPE_ID);
